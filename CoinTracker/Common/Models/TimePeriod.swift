import Foundation

enum TimePeriod: String {
    case short = "3h"
    case day = "24h"
    case week = "7d"
    case month = "30d"
    case quarter = "3m"
    case year = "1y"
    case threeYears = "3y"
    case fiveYears = "5y"
}
